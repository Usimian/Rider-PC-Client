"""The trimmed MPC's QP, exported for the ESP32 solver benchmark (2026-11-03; firmware 'mpcbench').

    python3 sim/lqr/mpc_export.py     # writes firmware/esp32_rider_fw/src/mpc_bench_data.h

One real problem of the planner (mpc_plan.py) at the ESP32 size (SHAPE): captured EXPORT_STEP planner steps into a
full-stick start to 0.60 m/s on a ~19 % battery (motors x0.78), where the limits bind. Exported: the fixed matrices
-- A (the limit rows) and Minv, the inverse of ADMM's x-step matrix P + sigma I + rho A'A, so each iteration is
matrix-vector work only -- the sample's q, l, u, and Python's answer after the same iterations from a cold start (the
check the chip compares against), with the converged one for reference. The header is generated: rerun this after
changing mpc_plan.py's QP.
"""
import os

import numpy as np

import closed_loop as CL
import drive_design as DD
import mpc_plan as M
from dataclasses import replace
from model import Params

SHAPE = M.Shape(horizon=25, step_cycles=10, check_every=10, iters=50, late=True)
MOTOR, V, EXPORT_STEP = 0.78, 0.60, 8
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "firmware", "esp32_rider_fw", "src",
                   "mpc_bench_data.h")


class _Capture(M.MpcFirmware):
    def __init__(self, **kw):
        super().__init__(**kw)
        self.probs = []

    def _plan_acc(self, dt, stick, held, x, pitch):
        solving = self.cycle % self.shape.step_cycles == 0
        super()._plan_acc(dt, stick, held, x, pitch)
        if solving and held:
            self.probs.append((self.mpc.qp, self.mpc.q.copy(), self.mpc.lo.copy(), self.mpc.hi.copy()))


def fl(v):
    """A C++ float literal (always with a '.' or an exponent)."""
    t = f"{float(v):.9g}"
    return (t if ("." in t or "e" in t or "n" in t) else t + ".0") + "f"


def arr(name, a):
    flat = ", ".join(fl(v) for v in np.asarray(a, dtype=np.float64).ravel())
    return f"static const float {name}[{np.asarray(a).size}] = {{{flat}}};\n"


def main():
    CL.VMAX = 0.6
    p = replace(Params(), ku_over_b=Params().ku_over_b * MOTOR)
    fw = _Capture(motor=MOTOR, up_deg=DD.UP, shape=SHAPE)
    CL.run(p, fw, T=3.0, th0_deg=0.0, drive=(np.array([0.0, 2.0]), np.array([0.0, V])), log_all=True)
    qp, q, lo, hi = fw.probs[EXPORT_STEP]
    P, A = qp.P, qp.A
    Minv = np.linalg.inv(P + qp.sigma * np.eye(P.shape[0]) + qp.rho * A.T @ A)
    cold = M.Qp(P, A, rho=qp.rho, sigma=qp.sigma, alpha=qp.alpha, iters=SHAPE.iters, soft=qp.soft)
    x_ref = cold.solve(q, lo, hi, warm=np.zeros(P.shape[0]))
    conv = M.Qp(P, A, rho=qp.rho, sigma=qp.sigma, alpha=qp.alpha, iters=5000, soft=qp.soft)
    x_conv = conv.solve(q, lo, hi, warm=np.zeros(P.shape[0]))
    active = int(np.sum((A @ x_conv >= hi - 1e-3) | (A @ x_conv <= lo + 1e-3)))
    n, m = A.shape[1], A.shape[0]
    with open(OUT, "w") as f:
        f.write("// GENERATED by sim/lqr/mpc_export.py -- do not edit; rerun it after changing sim/lqr/mpc_plan.py's QP.\n")
        f.write(f"// One planner QP ({SHAPE.name}), {EXPORT_STEP} steps into a full-stick start to {V} m/s at motors x{MOTOR}\n")
        f.write(f"// ({active} of {m} limit rows active at the optimum). Read by main.cpp 'mpcbench'.\n#pragma once\n")
        f.write(f"#define MPCB_N {n}\n#define MPCB_M {m}\n#define MPCB_ITERS {SHAPE.iters}\n")
        f.write(f"static const float MPCB_RHO = {fl(qp.rho)}, MPCB_SIGMA = {fl(qp.sigma)}, MPCB_ALPHA = {fl(qp.alpha)}, "
                f"MPCB_SOFT = {fl(qp.soft)};\n")
        for name, a in (("MPCB_MINV", Minv), ("MPCB_A", A), ("MPCB_Q", q), ("MPCB_L", lo), ("MPCB_U", hi),
                        ("MPCB_X_REF", x_ref), ("MPCB_X_CONV", x_conv)):
            f.write(arr(name, a))
    print(f"wrote {os.path.relpath(OUT)}: {n} variables, {m} limit rows ({active} active at the optimum); "
          f"{SHAPE.iters} iterations from cold: max |x - converged| {np.max(np.abs(x_ref - x_conv)):.4f} "
          f"(x scale {np.max(np.abs(x_conv)):.3f}); first jerk {x_ref[0] * M.J_SCALE:+.2f} m/s^3 (converged "
          f"{x_conv[0] * M.J_SCALE:+.2f})")


if __name__ == "__main__":
    main()
